    private void configurarColumnaTomarCaso() {

        // Configurar el boton que aparecera en cada fila
        tblTickets.getColumnModel().getColumn(7)
                .setCellRenderer(new javax.swing.table.TableCellRenderer() {
                    @Override
                    public java.awt.Component getTableCellRendererComponent(
                            javax.swing.JTable table, Object value,
                            boolean isSelected, boolean hasFocus,
                            int row, int column) {
                        javax.swing.JButton boton = new javax.swing.JButton();
                        String texto = value == null ? "Tomar Caso" : value.toString();
                        boton.setText(texto);
                        boton.setBackground(new java.awt.Color(38, 49, 68));
                        boton.setForeground(java.awt.Color.WHITE);
                        return boton;
                    }
                });

        // Configurar la accion del boton
        tblTickets.getColumnModel().getColumn(7)
                .setCellEditor(new javax.swing.DefaultCellEditor(new javax.swing.JCheckBox()) {
                    private final javax.swing.JButton boton = new javax.swing.JButton("Tomar Caso");
                    private int fila;

                    {
                        boton.setBackground(new java.awt.Color(38, 49, 68));
                        boton.setForeground(java.awt.Color.WHITE);
                        boton.addActionListener(e -> {
                            int filaModelo = tblTickets.convertRowIndexToModel(fila);
                            String codigo = tblTickets.getModel().getValueAt(filaModelo, 0).toString();
                            // Cambiar el estado del ticket
                            tblTickets.getModel().setValueAt("EN_PROCESO", filaModelo, 4);
                            // Cambiar el texto del boton
                            tblTickets.getModel().setValueAt("Tomado", filaModelo, 7);
                            javax.swing.JOptionPane.showMessageDialog(FormTicketTecnico.this, "Has tomado el caso: " + codigo);
                            fireEditingStopped();
                        });
                    }

                    @Override
                    public java.awt.Component getTableCellEditorComponent(
                            javax.swing.JTable table, Object value, boolean isSelected, int row, int column) {
                        fila = row;
                        String texto = value == null ? "Tomar Caso" : value.toString();
                        boton.setText(texto);
                        boton.setEnabled(!texto.equals("Tomado"));
                        return boton;
                    }

                    @Override
                    public Object getCellEditorValue() {
                        return "Tomado";
                    }
                });

        tblTickets.getColumnModel().getColumn(7).setPreferredWidth(110);
    }

