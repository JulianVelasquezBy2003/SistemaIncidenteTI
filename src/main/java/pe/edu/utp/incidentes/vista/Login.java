// Valida las credenciales contra la lista de personal.
    private void ingresar() {
        String user = usuario.getText().trim();
        String pass = new String(contrasena.getPassword());

        if (user.isEmpty() || pass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese usuario y contraseña.",
                    "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Persona autenticada = personal.stream()
                .filter(p -> p.validarCredenciales(user, pass))
                .findFirst()
                .orElse(null);

        if (autenticada == null) {
            JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos.",
                    "Acceso denegado", JOptionPane.ERROR_MESSAGE);
            contrasena.setText("");
            contrasena.requestFocusInWindow();
            return;
        }
        abrirSegunRol(autenticada);
    }

    // Abre el formulario que corresponde al rol del usuario y cierra el login.
    private void abrirSegunRol(Persona persona) {
        javax.swing.JFrame ventana = switch (persona.getRol()) {
            case SOLICITANTE ->
                new FormTicketSolicitante(persona, personal);
            case TECNICO ->
                new FormTicketTecnico(persona, personal);
            case ADMIN ->
                new FormPrincipal(persona, personal);
        };
        ventana.setLocationRelativeTo(null);
        ventana.setVisible(true);
        dispose();
    }

