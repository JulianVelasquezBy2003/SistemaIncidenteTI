    // Habilita el tipo de cliente (SOLICITANTE) o la especialidad (TECNICO).
    private void habilitarCamposPorRol() {
        int rol = cmbRol.getSelectedIndex();
        cmbTipoCliente.setEnabled(rol == 0);
        cmbEspecialidad.setEnabled(rol == 1);
    }

    // Verifica que haya un usuario elegido en la tabla.
    private boolean hayUsuarioSeleccionado() {
        if (tblPersonal.getSelectedRow() == -1) {
            Mensajes.advertencia(this, "Seleccione un usuario de la tabla.");
            return false;
        }
        return true;
    }

    /**
     * Valida los campos obligatorios.
     * @param exigirContrasena true al registrar; al modificar puede quedar vacía
     * @return true si los datos son correctos
     */
    private boolean validarCampos(boolean exigirContrasena) {
        if (txtId.getText().trim().isEmpty()) {
            Mensajes.advertencia(this, "Ingrese el ID del usuario.");
            txtId.requestFocusInWindow();
            return false;
        }
        if (txtNombre.getText().trim().isEmpty()) {
            Mensajes.advertencia(this, "Ingrese el nombre completo.");
            txtNombre.requestFocusInWindow();
            return false;
        }
        if (txtUsuario.getText().trim().isEmpty()) {
            Mensajes.advertencia(this, "Ingrese el nombre de usuario.");
            txtUsuario.requestFocusInWindow();
            return false;
        }
        if (exigirContrasena && new String(pwdContrasena.getPassword()).isEmpty()) {
            Mensajes.advertencia(this, "Ingrese la contraseña.");
            pwdContrasena.requestFocusInWindow();
            return false;
        }
        String correo = txtCorreo.getText().trim();
        if (correo.isEmpty() || !correo.contains("@")) {
            Mensajes.advertencia(this, "Ingrese un correo válido.");
            txtCorreo.requestFocusInWindow();
            return false;
        }
        return true;
    }

    // Deja todos los campos vacíos y quita la selección de la tabla.
    private void limpiarCampos() {
        txtId.setText("");
        txtNombre.setText("");
        txtUsuario.setText("");
        pwdContrasena.setText("");
        txtCorreo.setText("");
        cmbRol.setSelectedIndex(0);
        cmbTipoCliente.setSelectedIndex(0);
        cmbEspecialidad.setSelectedIndex(0);
        txtCarga.setText("0");
        tblPersonal.clearSelection();
        habilitarCamposPorRol();
        txtId.requestFocusInWindow();
    }

    // Copia la fila elegida de la tabla a los campos (la contraseña nunca se muestra).
    private void cargarFilaSeleccionada() {
        int fila = tblPersonal.getSelectedRow();
        if (fila == -1) {
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) tblPersonal.getModel();
        txtId.setText(texto(modelo, fila, 0));
        txtNombre.setText(texto(modelo, fila, 1));
        txtUsuario.setText(texto(modelo, fila, 2));
        txtCorreo.setText(texto(modelo, fila, 3));
        cmbRol.setSelectedItem(texto(modelo, fila, 4));
        String detalle = texto(modelo, fila, 5);
        if (cmbRol.getSelectedIndex() == 0) {
            cmbTipoCliente.setSelectedItem(detalle);
        } else if (cmbRol.getSelectedIndex() == 1) {
            cmbEspecialidad.setSelectedItem(detalle);
        }
        txtCarga.setText(texto(modelo, fila, 6));
        pwdContrasena.setText("");
        habilitarCamposPorRol();
    }

    // Lee el texto de una celda del modelo (vacío si no hay valor).
    private String texto(DefaultTableModel modelo, int fila, int columna) {
        Object valor = modelo.getValueAt(fila, columna);
        return (valor == null) ? "" : valor.toString();
    }

