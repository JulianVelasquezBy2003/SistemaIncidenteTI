    // Activa solo los campos del tipo de ticket elegido en cmbTipo.
    private void mostrarDetalleSegunTipo() {
        int tipo = cmbTipo.getSelectedIndex();
        boolean esIncidente = (tipo == 0);
        boolean esServicio = (tipo == 1);
        boolean esCambio = (tipo == 2);

        chkCritico.setEnabled(esIncidente);
        txtMinutos.setEnabled(esIncidente);
        txtPenalizacion.setEnabled(esIncidente);

        chkAprobadaJefatura.setEnabled(esServicio);
        txtJefeAprobador.setEnabled(esServicio);

        cmbRiesgo.setEnabled(esCambio);
        txtVentana.setEnabled(esCambio);
        txaRollback.setEnabled(esCambio);
        chkAprobado.setEnabled(esCambio);
    }

    /*
     * Habilita los botones según el rol:
     *  - SOLICITANTE: crea requerimientos, consulta sus tickets y cierra su caso.
     *  - TECNICO: ve su cola, gestiona el diagnóstico, escala y resuelve.
     *  - ADMIN: puede usar todas las opciones (asigna técnicos y elimina).
     */
    private void aplicarPermisosPorRol() {
        if (usuarioActual == null) {
            return;
        }
        lblSesion.setText("Sesión: " + usuarioActual.getNombre() + " (" + usuarioActual.getRol() + ")");
        Rol rol = usuarioActual.getRol();
        boolean esSolicitante = (rol == Rol.SOLICITANTE);
        boolean esTecnico = (rol == Rol.TECNICO);
        boolean esAdmin = (rol == Rol.ADMIN);

        btnNuevo.setEnabled(esSolicitante || esAdmin);
        btnCrear.setEnabled(esSolicitante || esAdmin);
        btnCerrarCaso.setEnabled(esSolicitante || esAdmin);

        btnAsignar.setEnabled(esAdmin);
        cmbTecnico.setEnabled(esAdmin);
        btnActualizar.setEnabled(esAdmin);
        btnEliminar.setEnabled(esAdmin);

        btnDiagnostico.setEnabled(esTecnico || esAdmin);
        btnEscalar.setEnabled(esTecnico || esAdmin);
        btnResolver.setEnabled(esTecnico || esAdmin);
        btnCola.setEnabled(esTecnico || esAdmin);
        cmbEstado.setEnabled(esTecnico || esAdmin);
        txaNotas.setEditable(esTecnico || esAdmin);
        txaSolucion.setEditable(esTecnico || esAdmin);

        // El solicitante solo ve sus propios tickets
        chkSoloMios.setSelected(!esAdmin);
        chkSoloMios.setEnabled(!esSolicitante);
    }

    // Verifica que haya un ticket elegido en la tabla.
    private boolean hayTicketSeleccionado() {
        if (tblTickets.getSelectedRow() == -1) {
            Mensajes.advertencia(this, "Seleccione un ticket de la tabla.");
            return false;
        }
        return true;
    }

    // Valida los datos mínimos de un ticket: título y descripción.
    private boolean validarDatosBasicos() {
        if (txtTitulo.getText().trim().isEmpty()) {
            Mensajes.advertencia(this, "Ingrese el título del requerimiento.");
            txtTitulo.requestFocusInWindow();
            return false;
        }
        if (txaDescripcion.getText().trim().isEmpty()) {
            Mensajes.advertencia(this, "Ingrese la descripción del requerimiento.");
            txaDescripcion.requestFocusInWindow();
            return false;
        }
        return true;
    }

    // Deja el formulario listo para registrar un nuevo ticket.
    private void limpiarFormulario() {
        txtCodigo.setText("");
        cmbTipo.setSelectedIndex(0);
        txtTitulo.setText("");
        txaDescripcion.setText("");
        cmbPrioridad.setSelectedIndex(0);
        cmbEstado.setSelectedIndex(0);
        txtSolicitante.setText("");
        cmbTecnico.setSelectedIndex(0);
        txtFecha.setText("");
        chkCritico.setSelected(false);
        txtMinutos.setText("");
        txtPenalizacion.setText("");
        chkAprobadaJefatura.setSelected(false);
        txtJefeAprobador.setText("");
        cmbRiesgo.setSelectedIndex(0);
        txtVentana.setText("");
        txaRollback.setText("");
        chkAprobado.setSelected(false);
        txaNotas.setText("");
        txaSolucion.setText("");
        tblTickets.clearSelection();
        txtTitulo.requestFocusInWindow();
    }

    // Lee el texto de una celda de la tabla (vacío si no hay valor).
    private String valorCelda(int fila, int columna) {
        Object valor = tblTickets.getValueAt(fila, columna);
        return (valor == null) ? "" : valor.toString();
    }

    // Copia la fila elegida de la tabla a los campos del formulario.
    private void cargarFilaSeleccionada() {
        int fila = tblTickets.getSelectedRow();
        if (fila == -1) {
            return;
        }
        txtCodigo.setText(valorCelda(fila, 0));
        cmbTipo.setSelectedItem(valorCelda(fila, 1));
        txtTitulo.setText(valorCelda(fila, 2));
        cmbPrioridad.setSelectedItem(valorCelda(fila, 3));
        cmbEstado.setSelectedItem(valorCelda(fila, 4));
        txtSolicitante.setText(valorCelda(fila, 5));
        cmbTecnico.setSelectedItem(valorCelda(fila, 6));
        txtFecha.setText(valorCelda(fila, 7));
        // TODO: cargar también descripción, notas, solución y los campos del tipo de ticket
    }

