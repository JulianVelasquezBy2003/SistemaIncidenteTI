    private void btnGuardarLimitesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarLimitesActionPerformed
        // Los tres límites deben ser números enteros mayores que cero
        try {
            int alta = Integer.parseInt(txtLimiteAlta.getText().trim());
            int media = Integer.parseInt(txtLimiteMedia.getText().trim());
            int baja = Integer.parseInt(txtLimiteBaja.getText().trim());
            if (alta <= 0 || media <= 0 || baja <= 0) {
                Mensajes.advertencia(this, "Los límites deben ser mayores que cero.");
                return;
            }
            if (alta > media || media > baja) {
                Mensajes.advertencia(this, "El límite de ALTA no puede superar al de MEDIA, ni este al de BAJA.");
                return;
            }
        } catch (NumberFormatException ex) {
            Mensajes.error(this, "Ingrese solo números enteros en los límites.");
            return;
        }
        // TODO: guardar los límites y recalcular el estado SLA de los tickets
        Mensajes.pendiente(this, "Aplicar límites SLA");
    }//GEN-LAST:event_btnGuardarLimitesActionPerformed

